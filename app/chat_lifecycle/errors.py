    TOOL_DENIED = "TOOL_DENIED"
    TOOL_VALIDATION_FAILED = "TOOL_VALIDATION_FAILED"
    DATA_ACCESS_DENIED = "DATA_ACCESS_DENIED"
    EXECUTION_INTERRUPTED = "EXECUTION_INTERRUPTED"
    INTERNAL_ERROR = "INTERNAL_ERROR"
